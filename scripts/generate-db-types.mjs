import { writeFile } from "node:fs/promises";
import { format } from "prettier";
import { createDatabase } from "../tests/helpers/database.mjs";

// Generate against the exact committed migrations, without hosted credentials.
const db = await createDatabase();
try {
  const { rows: columns } =
    await db.query(`select table_name,column_name,udt_name,is_nullable,column_default
    from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
  const tables = [...new Set(columns.map((c) => c.table_name))];
  const scalar = (name) =>
    ["uuid", "text", "varchar", "date", "time", "timestamptz"].includes(name)
      ? "string"
      : name === "bool"
        ? "boolean"
        : ["int2", "int4", "int8", "float4", "float8", "numeric"].includes(name)
          ? "number"
          : ["json", "jsonb"].includes(name)
            ? "Json"
            : name === "void"
              ? "undefined"
              : tables.includes(name)
                ? `Database['public']['Tables']['${name}']['Row']`
                : "unknown";
  const field = (c, mode) =>
    `          ${c.column_name}${mode === "Update" || (mode === "Insert" && (c.column_default || c.is_nullable === "YES")) ? "?" : ""}: ${scalar(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
  let output = `// Generated by npm run db:types from committed migrations. Do not edit manually.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = {\n  public: {\n    Tables: {\n`;
  for (const table of tables) {
    output += `      ${table}: {\n`;
    for (const mode of ["Row", "Insert", "Update"])
      output += `        ${mode}: {\n${columns
        .filter((c) => c.table_name === table)
        .map((c) => field(c, mode))
        .join("\n")}\n        };\n`;
    output += `        Relationships: [];\n      };\n`;
  }
  output += `    };\n    Views: { [_ in never]: never };\n    Functions: {\n`;
  const { rows: functions } =
    await db.query(`select p.proname,p.proargnames,p.pronargdefaults,
    array(select t.typname from unnest(p.proargtypes::oid[]) with ordinality a(id,n) join pg_type t on t.oid=a.id order by a.n) as args,
    t.typname as return_type from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype
    where n.nspname='public' order by p.proname`);
  for (const f of functions) {
    output += `      ${f.proname}: { Args: { ${f.args.map((a, i) => `${f.proargnames[i]}${i >= f.args.length - f.pronargdefaults ? "?" : ""}: ${scalar(a)}`).join("; ")} }; Returns: ${scalar(f.return_type)} };\n`;
  }
  output += `    };\n    Enums: { [_ in never]: never };\n    CompositeTypes: { [_ in never]: never };\n  };\n};\nexport type Row<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\n`;
  await writeFile(
    new URL("../src/lib/database.types.ts", import.meta.url),
    await format(output, { parser: "typescript" }),
  );
  console.log(
    "Generated src/lib/database.types.ts from migrated PostgreSQL schema.",
  );
} finally {
  await db.close();
}
